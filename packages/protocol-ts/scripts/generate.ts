// Generates src/generated/{types,schemas}.ts from contracts/protocol (the source of truth).
// Run: pnpm --filter @ssc/protocol generate. test/generated.test.ts fails if the output is stale.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
export const PROTOCOL_DIR = resolve(here, "../../../contracts/protocol");
export const OUT_DIR = resolve(here, "../src/generated");

const BANNER = "// GENERATED by scripts/generate.ts from contracts/protocol. Do not edit by hand.\n";

interface SchemaFile {
  /** "envelope", "qr" or the message type, e.g. "answer.delta". */
  name: string;
  schema: Record<string, unknown>;
}

export function readSchemas(): { envelope: SchemaFile; qr: SchemaFile; messages: SchemaFile[] } {
  const load = (p: string) => JSON.parse(readFileSync(p, "utf8")) as Record<string, unknown>;
  const messages = readdirSync(join(PROTOCOL_DIR, "messages"))
    .filter((f) => f.endsWith(".schema.json"))
    .sort()
    .map((f) => ({ name: f.replace(/\.schema\.json$/, ""), schema: load(join(PROTOCOL_DIR, "messages", f)) }));
  return {
    envelope: { name: "envelope", schema: load(join(PROTOCOL_DIR, "envelope.schema.json")) },
    qr: { name: "qr", schema: load(join(PROTOCOL_DIR, "qr.schema.json")) },
    messages,
  };
}

export async function generate(): Promise<Record<string, string>> {
  const { envelope, qr, messages } = readSchemas();
  let types = BANNER;
  for (const s of [envelope, qr, ...messages]) {
    // Strip $id so the compiler does not try to resolve it; titles drive the type names.
    const { $id: _id, ...schema } = s.schema;
    const ts = await compile(schema as never, String(s.schema.title), {
      bannerComment: "",
      additionalProperties: false,
      strictIndexSignatures: true,
      declareExternallyReferenced: true,
      format: true,
      ignoreMinAndMaxItems: true,
      style: { printWidth: 110 },
    });
    types += `\n// ---- ${s.name} ----\n${ts}`;
  }

  const typeNames = messages.map((m) => `  ${JSON.stringify(m.name)}: ${String(m.schema.title)};`).join("\n");
  types += `\n/** Message type -> payload type. */\nexport interface PayloadMap {\n${typeNames}\n}\n`;

  let schemas = BANNER;
  schemas += `/* eslint-disable */\n`;
  schemas += `export const ENVELOPE_SCHEMA: Record<string, unknown> = ${JSON.stringify(envelope.schema, null, 2)};\n\n`;
  schemas += `export const QR_SCHEMA: Record<string, unknown> = ${JSON.stringify(qr.schema, null, 2)};\n\n`;
  schemas += `export const MESSAGE_TYPES = ${JSON.stringify(messages.map((m) => m.name))} as const;\n\n`;
  schemas += `export const MESSAGE_SCHEMAS: Record<(typeof MESSAGE_TYPES)[number], Record<string, unknown>> = {\n`;
  for (const m of messages) schemas += `  ${JSON.stringify(m.name)}: ${JSON.stringify(m.schema)},\n`;
  schemas += `};\n`;

  return { "types.ts": types, "schemas.ts": schemas };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = await generate();
  mkdirSync(OUT_DIR, { recursive: true });
  for (const [f, content] of Object.entries(out)) writeFileSync(join(OUT_DIR, f), content);
  console.log(`generated ${Object.keys(out).join(", ")} in ${OUT_DIR}`);
}
